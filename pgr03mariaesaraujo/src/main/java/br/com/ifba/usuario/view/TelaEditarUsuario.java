    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String login = txtLogin.getText().trim();
        String email = txtEmail.getText().trim();
        String telefone = txtTelefone.getText().trim();
        String genero = boxGenero.getSelectedItem().toString();

        if (login.isEmpty() || email.isEmpty() || telefone.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Preencha todos os campos.",
                    "Aviso",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        EntityManager em = JPAUtil.getEntityManager();

        try {
            em.getTransaction().begin();

            Usuario usuario = em.find(Usuario.class, cpfUsuario);

            if (usuario == null) {
                em.getTransaction().rollback();

                JOptionPane.showMessageDialog(
                        this,
                        "Usuário não encontrado.",
                        "Erro",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            usuario.setLogin(login);
            usuario.setEmail(email);
            usuario.setTel(telefone);
            usuario.setGenero(genero);

            em.getTransaction().commit();

            JOptionPane.showMessageDialog(
                    this,
                    "Dados atualizados com sucesso!",
                    "Sucesso",
                    JOptionPane.INFORMATION_MESSAGE
            );

            dispose();

        } catch (RuntimeException e) {
            if (em.getTransaction().isActive()) {
                em.getTransaction().rollback();
            }

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao atualizar usuário: " + e.getMessage(),
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        } finally {
            em.close();
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

